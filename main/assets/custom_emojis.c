const lv_image_dsc_t* GetCustomEmojiImage(const char* emotion) {
    if (emotion == NULL || emotion[0] == '\0') return NULL;
    for (size_t i = 0; i < sizeof(emoji_maps)/sizeof(emoji_maps[0]); i++) {
        if (strcmp(emoji_maps[i].name, emotion) == 0) {
            return emoji_maps[i].img;
        }
    }
    for (size_t i = 0; i < sizeof(emoji_maps)/sizeof(emoji_maps[0]); i++) {
        if (strcmp(emoji_maps[i].name, "neutral") == 0 || strcmp(emoji_maps[i].name, "bieucam-macdinh") == 0) {
            return emoji_maps[i].img;
        }
    }
    if (sizeof(emoji_maps)/sizeof(emoji_maps[0]) > 0) return emoji_maps[0].img;
    return NULL;
}